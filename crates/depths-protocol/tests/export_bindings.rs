//! Regenerates the TypeScript protocol bindings in `apps/depths/web/src/protocol/generated/`
//! (spec 050 T034).
//!
//! Run with `cargo test -p depths-protocol --test export_bindings`. The output is committed, so a
//! diff after running this means the Rust protocol changed and the web must follow
//! (`scripts/ci.sh` checks).
//!
//! `u64`/`i64` are emitted as `number` (not `bigint`): JSON carries them as plain numbers and every
//! such field (request and stream ids, byte counts) stays below 2^53 in practice.

use depths_protocol::{
    CloseCode, CmdEnvelope, EventEnvelope, Hello, MAX_STREAMS_PER_SOCKET, Me, PROTOCOL_VERSION,
};
use std::fmt::Write as _;
use std::path::PathBuf;
use ts_rs::{Config, TS};

/// Hand-written alongside the generated types: values, not types, so `export *`.
const CONSTANTS: &str = "constants";

#[test]
fn export_typescript_bindings() {
    let out_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../apps/depths/web/src/protocol/generated");
    std::fs::create_dir_all(&out_dir).unwrap();

    // Start clean so types removed from Rust disappear from the web.
    for entry in std::fs::read_dir(&out_dir).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().is_some_and(|ext| ext == "ts") {
            std::fs::remove_file(path).unwrap();
        }
    }

    let cfg = Config::new()
        .with_large_int("number")
        .with_out_dir(&out_dir);
    Hello::export_all(&cfg).unwrap();
    CmdEnvelope::export_all(&cfg).unwrap();
    EventEnvelope::export_all(&cfg).unwrap();
    Me::export_all(&cfg).unwrap();

    let mut constants = String::from(
        "// This file was generated by `cargo test -p depths-protocol --test export_bindings`. Do not edit it manually.\n\n",
    );
    writeln!(
        constants,
        "/** The version a client states in `Hello.protocol_version`. */\nexport const PROTOCOL_VERSION = {PROTOCOL_VERSION} as const;\n"
    )
    .unwrap();
    writeln!(
        constants,
        "/** Most open streams (log follows, shells and the stats watch) on one socket. */\nexport const MAX_STREAMS_PER_SOCKET = {MAX_STREAMS_PER_SOCKET} as const;\n"
    )
    .unwrap();
    constants.push_str("/** WebSocket close codes. */\nexport const CloseCode = {\n");
    for code in CloseCode::ALL {
        writeln!(constants, "  {}: {},", code.name(), code.code()).unwrap();
    }
    constants.push_str("} as const;\n");
    std::fs::write(out_dir.join(format!("{CONSTANTS}.ts")), constants).unwrap();

    let mut names: Vec<String> = std::fs::read_dir(&out_dir)
        .unwrap()
        .filter_map(|e| {
            let path = e.unwrap().path();
            let stem = path.file_stem()?.to_str()?.to_owned();
            (path.extension()? == "ts" && stem != "index" && stem != CONSTANTS).then_some(stem)
        })
        .collect();
    names.sort();
    for required in [
        "Cmd",
        "CmdEnvelope",
        "Event",
        "EventEnvelope",
        "Hello",
        "Me",
        "Container",
    ] {
        assert!(names.iter().any(|n| n == required), "missing {required}");
    }

    let mut index = String::from(
        "// This file was generated by `cargo test -p depths-protocol --test export_bindings`. Do not edit it manually.\n",
    );
    for name in &names {
        writeln!(index, "export type * from \"./{name}\";").unwrap();
    }
    writeln!(index, "export * from \"./{CONSTANTS}\";").unwrap();
    std::fs::write(out_dir.join("index.ts"), index).unwrap();
}
