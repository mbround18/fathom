//! Regenerates the TypeScript protocol bindings in `ui/src/protocol/generated/` (T021).
//!
//! Run with `cargo test -p fathom --test export_bindings`. The output is committed, so a
//! diff after running this means the Rust protocol changed and the UI must follow.
//!
//! `u64`/`i64` are emitted as `number` (not `bigint`): JSON carries them as plain numbers
//! and every such field (seq, ids, byte counts, timestamps) stays below 2^53 in practice.

use fathom::protocol::{
    BackendCmdV1, BackendEventEnvelopeV1, BridgeError, DevBridgeClientMsg, DevBridgeServerMsg,
    EventBatch, RequestId, SubscriptionInfo, UiConfig,
};
use std::fmt::Write as _;
use std::path::PathBuf;
use ts_rs::{Config, TS};

/// Unversioned aliases re-exported from `index.ts`, mirroring `fathom::protocol`.
const ALIASES: &[(&str, &str)] = &[
    ("BackendCmdV1", "BackendCmd"),
    ("BackendEventEnvelopeV1", "BackendEventEnvelope"),
    ("BackendEventV1", "BackendEvent"),
];

#[test]
fn export_typescript_bindings() {
    let out_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("ui/src/protocol/generated");
    std::fs::create_dir_all(&out_dir).unwrap();

    // Start clean so types removed from Rust disappear from the UI.
    for entry in std::fs::read_dir(&out_dir).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().is_some_and(|ext| ext == "ts") {
            std::fs::remove_file(path).unwrap();
        }
    }

    let cfg = Config::new()
        .with_large_int("number")
        .with_out_dir(&out_dir);
    BackendCmdV1::export_all(&cfg).unwrap();
    BackendEventEnvelopeV1::export_all(&cfg).unwrap();
    UiConfig::export_all(&cfg).unwrap();
    EventBatch::export_all(&cfg).unwrap();
    SubscriptionInfo::export_all(&cfg).unwrap();
    BridgeError::export_all(&cfg).unwrap();
    RequestId::export_all(&cfg).unwrap();
    DevBridgeClientMsg::export_all(&cfg).unwrap();
    DevBridgeServerMsg::export_all(&cfg).unwrap();

    let mut names: Vec<String> = std::fs::read_dir(&out_dir)
        .unwrap()
        .filter_map(|e| {
            let path = e.unwrap().path();
            let stem = path.file_stem()?.to_str()?.to_owned();
            (path.extension()? == "ts" && stem != "index").then_some(stem)
        })
        .collect();
    names.sort();
    assert!(
        names.len() > 100,
        "expected the full protocol, got {names:?}"
    );

    let mut index = String::from(
        "// This file was generated by `cargo test -p fathom --test export_bindings`. Do not edit it manually.\n",
    );
    for name in &names {
        writeln!(index, "export type * from \"./{name}\";").unwrap();
    }
    index.push('\n');
    for (versioned, alias) in ALIASES {
        assert!(names.iter().any(|n| n == versioned), "missing {versioned}");
        writeln!(
            index,
            "export type {{ {versioned} as {alias} }} from \"./{versioned}\";"
        )
        .unwrap();
    }
    std::fs::write(out_dir.join("index.ts"), index).unwrap();
}
