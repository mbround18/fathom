#!/usr/bin/env bash
# Regenerate THIRD_PARTY_LICENSES.md: every Rust crate in Cargo.lock and every production npm
# package in ui/pnpm-lock.yaml, with version and licence expression. Names and licences only; the
# full texts ship with each package.
#
#   scripts/third-party-licenses.sh            # writes THIRD_PARTY_LICENSES.md at the repo root
#
# Needs cargo and pnpm (with ui/node_modules installed: `pnpm -C ui install --frozen-lockfile`).
# Set CARGO_OFFLINE=1 to resolve the Rust side from the local registry cache only.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/THIRD_PARTY_LICENSES.md"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

offline=()
[ "${CARGO_OFFLINE:-0}" = "1" ] && offline=(--offline)
(cd "$root" && cargo metadata --format-version 1 --locked "${offline[@]}") > "$tmp/cargo.json"
(cd "$root/ui" && pnpm licenses list --prod --json) > "$tmp/npm.json"

python3 -I - "$tmp/cargo.json" "$tmp/npm.json" > "$out" <<'PY'
import json, sys

cargo = json.load(open(sys.argv[1]))
npm = json.load(open(sys.argv[2]))

members = set(cargo["workspace_members"])
crates = sorted(
    ((p["name"], p["version"], p.get("license") or ("see " + p["license_file"] if p.get("license_file") else "UNKNOWN"))
     for p in cargo["packages"] if p["id"] not in members),
    key=lambda r: (r[0].lower(), r[1]),
)
packages = sorted(
    ((e["name"], v, lic) for lic, entries in npm.items() for e in entries for v in e["versions"]),
    key=lambda r: (r[0].lower(), r[1]),
)

def cell(s):
    return str(s).replace("|", "\\|")

def table(rows):
    print("| Name | Version | Licence |")
    print("|---|---|---|")
    for name, version, lic in rows:
        print(f"| {cell(name)} | {cell(version)} | {cell(lic)} |")

print("# Third-party licences")
print()
print("Generated by `scripts/third-party-licenses.sh` from `Cargo.lock` and `ui/pnpm-lock.yaml`.")
print("Do not edit by hand. Licence texts ship inside each package; this file lists names,")
print("versions and SPDX expressions only.")
print()
print(f"## Rust crates ({len(crates)})")
print()
table(crates)
print()
print(f"## npm packages, production dependencies of `ui/` ({len(packages)})")
print()
table(packages)
PY

echo "wrote $out"
