#!/usr/bin/env python3
"""Regenerate 045's requirements checklist from spec.md and tasks.md.

The checklist's job (T075) is to make an unimplemented requirement visible, so it is
derived rather than hand-maintained: an FR is checked only when every task that cites
it is marked [X] in tasks.md. Re-run this after any task lands.
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SPEC = HERE / 'specs/045-guided-oidc-setup/spec.md'
TASKS = HERE / 'specs/045-guided-oidc-setup/tasks.md'
OUT = HERE / 'specs/045-guided-oidc-setup/checklists/requirements.md'

frs = {}
for line in SPEC.read_text().splitlines():
    m = re.match(r'- \*\*(FR-\d{3})\*\*:\s*(.+)', line)
    if m:
        frs[m.group(1)] = m.group(2).strip()

# task id -> (done, FRs it cites)
tasks = {}
for line in TASKS.read_text().splitlines():
    m = re.match(r'- \[([ Xx])\] (T\d{3}) (.*)', line)
    if m:
        # Strip ranges like `FR-001-FR-036` first: a task that names the whole span (T075
        # describes itself that way) is not a citation of its endpoints.
        body = re.sub(r'FR-\d{3}\s*[\u2013\u2014-]\s*FR-\d{3}', '', m.group(3))
        tasks[m.group(2)] = (m.group(1) in 'Xx', set(re.findall(r'FR-\d{3}', body)))

by_fr = {fr: sorted(t for t, (_, cited) in tasks.items() if fr in cited) for fr in frs}

lines = [
    '# Requirements coverage: 045-guided-oidc-setup',
    '',
    'Generated by `scripts/gen-045-requirements.py` from `spec.md` and `tasks.md` — do not',
    'hand-edit. An `FR` is checked only when every task citing it is marked `[X]` in',
    '`tasks.md`, so a requirement nothing has implemented stays visibly unchecked.',
    '',
    '## Functional requirements',
    '',
]
orphans = []
for fr, text in sorted(frs.items()):
    ids = by_fr[fr]
    if not ids:
        orphans.append(fr)
        mark, where = ' ', '**no task cites this requirement**'
    else:
        mark = 'X' if all(tasks[t][0] for t in ids) else ' '
        where = ', '.join(f'`{t}`' + ('' if tasks[t][0] else ' (open)') for t in ids)
    short = text if len(text) <= 150 else text[:149].rstrip() + '…'
    lines += [f'- [{mark}] **{fr}** — {short}', f'  - {where}', '']

done = sum(1 for fr in frs if by_fr[fr] and all(tasks[t][0] for t in by_fr[fr]))
lines += [
    '## Gaps',
    '',
]
if orphans:
    lines += [
        'These requirements are cited by no task in `tasks.md`. They may still be satisfied',
        'incidentally by a task that does not name them, but nothing in the task list is',
        'accountable for them:',
        '',
    ] + [f'- **{fr}** — {frs[fr]}' for fr in orphans] + ['']
else:
    lines += ['No requirement is left uncited by `tasks.md`.', '']
lines += [f'## Totals', '', f'{done} of {len(frs)} requirements have all their tasks complete.', '']
OUT.write_text('\n'.join(lines))
print(f'{OUT.relative_to(HERE)}: {done}/{len(frs)} complete, {len(orphans)} uncited')
